#!/usr/bin/env python3
"""Usage: gen-tabler-glyphs.py tabler.json OUT.h -- the Tabler catalog as relocation-free constant tables: names in
one string blob, entries sorted by name (binary search), so the catalog is shared read-only pages, not heap."""
import json
import sys


def main():
    src, out = sys.argv[1], sys.argv[2]
    with open(src, encoding="utf-8") as f:
        data = json.load(f)
    entries = []
    for name, value in data.items():
        cp = value.get("codepoint", "")
        if not cp.startswith("U+"):
            continue
        code = int(cp[2:], 16)
        if code == 0 or code > 0x10FFFF:
            continue
        encoded = name.encode("utf-8")
        assert len(encoded) < 256, name
        entries.append((encoded, code, value.get("category", "")))
    entries.sort(key=lambda e: e[0])
    categories = sorted({e[2] for e in entries})
    cat_index = {c: i for i, c in enumerate(categories)}
    blob = bytearray()
    rows = []
    for name, code, cat in entries:
        rows.append(f"{{{len(blob)}u, {len(name)}u, {cat_index[cat]}u, 0x{code:X}u}}")
        blob += name
    with open(out, "w", encoding="utf-8") as f:
        f.write("// Generated by gen-tabler-glyphs.py from tabler.json. Do not edit.\n#pragma once\n\n")
        f.write("#include <array>\n#include <cstdint>\n#include <string_view>\n\nnamespace tabler_data {\n\n")
        f.write("  struct Entry {\n    std::uint32_t nameOffset;\n    std::uint8_t nameLength;\n")
        f.write("    std::uint8_t category;\n    std::uint32_t codepoint;\n  };\n\n")
        f.write(f"  inline constexpr char kNames[] = \"{''.join(f'{chr(b)}' if 32 <= b < 127 and b not in (34, 92, 63) else f'\\\\{b:03o}' for b in blob)}\";\n\n")
        f.write(f"  inline constexpr std::array<std::string_view, {len(categories)}> kCategories{{\n")
        f.write("".join(f"      \"{c}\",\n" for c in categories))
        f.write("  };\n\n")
        f.write(f"  inline constexpr std::array<Entry, {len(rows)}> kEntries{{{{\n")
        f.write("".join(f"      {r},\n" for r in rows))
        f.write("  }};\n\n} // namespace tabler_data\n")


if __name__ == "__main__":
    main()
